function hash(value: string) {
  let result = 0;
  for (let index = 0; index < value.length; index += 1) result = (result * 31 + value.charCodeAt(index)) >>> 0;
  return result;
}

function trimPost(value: string) {
  const compact = value.replace(/\n{3,}/g, "\n\n").trim();
  return compact.length <= 490 ? compact : `${compact.slice(0, 486).trimEnd()}…`;
}

function goalEnding(input: GenerationInput) {
  if (input.goal === "clicks") return "Если хотите посмотреть, как это может выглядеть на практике, вот пример: {tracking_url}";
  if (input.goal === "leads") return "Если хотите такой же понятный путь для своих клиентов, напишите мне. Посмотрю задачу и скажу, с чего лучше начать.";
  return "Проверьте свой путь клиента с телефона: понятно ли за минуту, что выбрать, сколько это стоит и куда нажать дальше?";
}

function makeCtas(input: GenerationInput, settings: OfferSettings) {
  const name = settings.performerName ? `, я — ${settings.performerName}` : "";
  const whatsapp = settings.whatsapp ? ` Можно написать в WhatsApp: ${settings.whatsapp}.` : "";
  const custom = settings.ctaText.trim();
  return [
    custom || `Если хотите понять, что можно упростить именно в вашем случае${name}, напишите мне. Задам несколько вопросов и предложу понятную структуру без лишних функций.`,
    input.city
      ? `Могу посмотреть, как сейчас устроен путь клиента у бизнеса в ${input.city}, и подсказать, где его можно сделать проще. Без обещаний и громких цифр — только конкретные замечания.${whatsapp}`
      : `Могу посмотреть, как сейчас устроен путь клиента в вашем бизнесе, и подсказать, где его можно сделать проще. Без обещаний и громких цифр — только конкретные замечания.${whatsapp}`,
    input.goal === "clicks"
      ? "Хотите увидеть пример такого подхода? Оставил его здесь: {tracking_url}"
      : `Если задача актуальна, напишите слово «сайт». Спокойно обсудим, какой формат подойдёт вашему бизнесу и нужен ли он сейчас вообще.`,
  ];
}

export function topicFor(category: ThreadsCategory, index: number, input: GenerationInput) {
  const angle = categoryTopics[category][index % categoryTopics[category].length];
  const frames = ["разбор", "чек-лист", "типичная ошибка", "путь клиента", "практичное решение", "вопрос перед запуском"];
  const audience = input.niche.toLowerCase() === "все заведения" ? "заведений и локального бизнеса" : `ниши «${input.niche}»`;
  return `${angle}: ${frames[Math.floor(index / categoryTopics[category].length) % frames.length]} для ${audience}`;
}

