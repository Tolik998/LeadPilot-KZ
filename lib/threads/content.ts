export function regeneratePart(input: GenerationInput, settings: OfferSettings, current: string[], partIndex: number) {
  const variants = [
    `Попробуйте пройти путь клиента самостоятельно, именно с телефона. Понятно ли с первого экрана, чем вы занимаетесь? Легко ли найти актуальные цены и условия? Видно ли, куда нажать, чтобы записаться или оформить заказ? Если на каждом этапе приходится что-то искать или уточнять, сайт можно сделать заметно проще.`,
    `Сначала стоит решить, что именно должен сделать посетитель: выбрать услугу, записаться на время, собрать заказ или написать с конкретным вопросом. После этого структура становится понятнее. На странице остаётся только то, что помогает человеку принять решение, а всё лишнее не отвлекает его от следующего шага.`,
    `Сайт имеет смысл, когда упрощает реальный процесс бизнеса. Каталог помогает выбрать, админ-панель — поддерживать информацию актуальной, WhatsApp — продолжить уже оформленный диалог, а автоматизация — не потерять обращение. Нужны не все функции сразу, а только те, которыми команда действительно будет пользоваться.`,
  ];
  const next = [...current];
  next[partIndex] = trimPost(variants[(hash(current.join("|")) + partIndex) % variants.length]);
  return next;
}
