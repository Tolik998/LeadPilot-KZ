export const dgisCategorySections: DgisCategorySection[] = categoryGroups.map(
  (group) => ({
    id: group.id,
    name: group.name,
    categories: group.queries.map((name) => ({
      id: `${group.id}:${name.toLocaleLowerCase("ru")}`,
      name,
      parentName: group.name,
    })),
  }),
);

export const dgisCategories = dgisCategorySections.flatMap(
  (section) => section.categories,
);

const categoryById = new Map(
  dgisCategories.map((category) => [category.id, category]),
);
const categoryByName = new Map(
  dgisCategories.map((category) => [
    category.name.toLocaleLowerCase("ru"),
    category,
  ]),
);

export function restoreDgisCategories(value: unknown): DgisCategory[] {
  if (!Array.isArray(value)) return [];
  const restored = new Map<string, DgisCategory>();
  for (const entry of value) {
    if (!entry || typeof entry !== "object") continue;
    const saved = entry as Partial<DgisCategory>;
    const name = typeof saved.name === "string" ? saved.name.trim() : "";
    if (!name) continue;
    const known =
      (typeof saved.id === "string" ? categoryById.get(saved.id) : undefined) ||
      categoryByName.get(name.toLocaleLowerCase("ru"));
    const category = known || {
      id: `saved:${name.toLocaleLowerCase("ru")}`,
      name,
      parentName:
        typeof saved.parentName === "string" && saved.parentName.trim()
          ? saved.parentName.trim()
          : "Сохранённые категории",
    };
    restored.set(category.id, category);
  }
  return [...restored.values()];
}
